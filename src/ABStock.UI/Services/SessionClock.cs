using ABStock.Application.MarketHistory;

namespace ABStock.UI.Services;

/// <summary>
/// Часы сессии: сколько она идёт, а после остановки — сколько она шла.
///
/// Живёт здесь, а не на странице, потому что часы показывают двое — «Торги» и
/// «Агенты», — и показывать они обязаны одно и то же число. Раздел 9.0: одно
/// число — один источник.
///
/// Два состояния считаются ПО-РАЗНОМУ, и это не мелочь. Пока сессия идёт,
/// длительность — это «сейчас минус старт». После остановки так считать
/// нельзя: страницу могли открыть через час, и «сейчас минус старт» показало
/// бы час вместо четырёх минут. Времени окончания в сводке прогона нет, но шаг
/// симуляции равен ровно секунде (<c>CreateSessionConfig</c>), поэтому число
/// тиков и есть длительность в секундах.
///
/// До пункта 106 эта разница была спрятана, а не решена: остановленный чип
/// показывал слова «сессия остановлена» вместо числа, и неверный расчёт просто
/// некуда было вывести.
/// </summary>
public static class SessionClock
{
    /// <summary>
    /// Длительность сессии или <see langword="null"/>, если прогона не было.
    /// </summary>
    public static TimeSpan? Elapsed(bool running, SimulationRunSummary? summary)
    {
        if (summary is null)
        {
            return null;
        }

        return running
            ? DateTimeOffset.Now - summary.StartedAt.ToLocalTime()
            : TimeSpan.FromSeconds(summary.TickCount);
    }

    /// <summary>
    /// То же в виде ЧЧ:ММ:СС (раздел 10) — или <see langword="null"/>, если
    /// прогона не было.
    ///
    /// Именно null, а не «00:00:00». Нули — это утверждение «сессия длилась
    /// ноль», то есть высказывание о сессии, которой не случилось; раздел 10
    /// запрещает подставлять ноль вместо отсутствующего значения. Кто зовёт,
    /// тот и решает, что показать вместо числа: чип часов — не показываться
    /// вовсе, панель итогов — прочерк.
    /// </summary>
    public static string? Format(bool running, SimulationRunSummary? summary) =>
        Elapsed(running, summary)?.ToString(@"hh\:mm\:ss");
}
