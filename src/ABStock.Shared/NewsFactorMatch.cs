namespace ABStock.Shared;

/// <summary>Какой стороной профиля новость попала в актив.</summary>
public enum NewsFactorKind
{
    Positive,
    Negative,
    Risk,
    Keyword
}

/// <summary>
/// Сработавший пункт профиля: что именно совпало и с каким куском новости.
///
/// Одних количеств мало. Экран «Новостей» обязан показать не «затронуто 3»,
/// а «позитивный · Ввод новых генерирующих мощностей · совпало с „третий блок
/// ТЭЦ“»: раздел 1 требует, чтобы причинность читалась с экрана без пояснений,
/// а раздел 16.3 — чтобы человек увидел превращение текста в торговый сигнал.
/// </summary>
/// <param name="Text">Формулировка пункта профиля, как её показывает «Создание актива».</param>
/// <param name="Excerpt">Фрагмент новости, на котором пункт сработал.</param>
public sealed record NewsFactorMatch(
    NewsFactorKind Kind,
    string Text,
    string Excerpt);
